// A small licensed application: activation input, status, and a real protected export.
package main

import (
	"bufio"
	"context"
	"fmt"
	licentivo "github.com/spf86/licentivo-sdk"
	"os"
	"strings"
	"time"
)

func main() {
	path := "product.json"
	if len(os.Args) > 1 {
		path = os.Args[1]
	}
	input := bufio.NewReader(os.Stdin)
	fmt.Print("License key / temporary transfer code (empty to restore): ")
	key, _ := input.ReadString('\n')
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	c, err := licentivo.OpenWithLicense(ctx, path, strings.TrimSpace(key), func(err error) { fmt.Println("Background verification:", err) })
	if err != nil {
		fmt.Println(err)
		return
	}
	defer c.Close()
	var pending *licentivo.Reservation
	job := ""
	for {
		fmt.Println("1 Export report  2 Metered export  3 Retry commit  4 Release device  5 Status  0 Exit")
		command, _ := input.ReadString('\n')
		command = strings.TrimSpace(command)
		if command == "0" || command == "" {
			return
		}
		switch command {
		case "5":
			fmt.Printf("%+v\n", c.Status())
		case "4":
			fmt.Println(c.Deactivate(ctx))
		case "3":
			if pending != nil {
				_, err = c.Commit(ctx, pending.ID, job)
				if err == nil {
					pending = nil
				}
				fmt.Println("Commit:", err)
			}
		case "1", "2":
			if pending != nil {
				fmt.Println("Finish the pending commit first.")
				continue
			}
			state := c.FeatureStatus("export")
			if !state.Allowed {
				fmt.Printf("Export denied: %+v\n", state)
				continue
			}
			job = fmt.Sprintf("export-%d", time.Now().UnixNano())
			if command == "2" {
				hold, e := c.Reserve(ctx, "export", 1, job)
				if e != nil {
					fmt.Println(e)
					continue
				}
				if hold.Status != "pending" {
					fmt.Println("Closed operation; do not export again.")
					continue
				}
				pending = &hold
			}
			if err = os.WriteFile("licensed-report.txt", []byte("A report generated by the licensed application.\n"), 0600); err != nil {
				if pending != nil {
					_, _ = c.Cancel(ctx, pending.ID, job)
					pending = nil
				}
				fmt.Println(err)
				continue
			}
			if pending != nil {
				_, err = c.Commit(ctx, pending.ID, job)
				if err == nil {
					pending = nil
				} else {
					fmt.Println("Report exists; retry only the commit:", err)
				}
			}
			fmt.Println("Report saved: licensed-report.txt")
		}
	}
}
