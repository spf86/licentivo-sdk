/* A customer application's activation screen and protected report operation. */
#include "licentivo.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>

static void line(char *value, size_t capacity) {
    if (!fgets(value, (int)capacity, stdin)) value[0] = 0;
    value[strcspn(value, "\r\n")] = 0;
}
static void show_error(ln_client *client) {
    ln_error_info error = {0}; ln_get_error_info(client, &error);
    fprintf(stderr, "%s; request=%s; retryable=%d\n", error.code, error.request_id, error.retryable);
}
static int write_report(void) {
    FILE *file = fopen("licensed-report.txt", "wb");
    if (!file) return 0;
    int ok = fputs("A report generated by the licensed application.\n", file) >= 0;
    return fclose(file) == 0 && ok;
}
int main(int argc, char **argv) {
    char key[80], command[24], job[80] = "", reservation[40] = "";
    const char *settings = argc > 1 ? argv[1] : "product.json";
    printf("License key / transfer code (empty to restore): "); line(key, sizeof(key));
    ln_client *client = ln_init_file_with_license(settings, key);
    if (!client) { fputs("Invalid product settings or missing activation key.\n", stderr); return 1; }
    if (!ln_start(client)) { show_error(client); ln_destroy(client); return 1; }
    for (;;) {
        puts("1 Export report  2 Metered export  3 Retry commit  4 Release device  5 Status  0 Exit");
        line(command, sizeof(command));
        if (!command[0] || !strcmp(command, "0")) break;
        if (!strcmp(command, "5")) { char *status = ln_status(client); puts(status ? status : "unavailable"); ln_free_string(status); }
        else if (!strcmp(command, "4")) { if (!ln_deactivate(client)) show_error(client); }
        else if (!strcmp(command, "3") && reservation[0]) {
            char *result = ln_commit(client, reservation, job);
            if (result) { reservation[0] = 0; puts("Commit confirmed."); } else show_error(client);
            ln_free_string(result);
        } else if (!strcmp(command, "1") || !strcmp(command, "2")) {
            if (reservation[0]) { puts("The report was written. Retry its commit before another export."); continue; }
            if (!ln_check_feature(client, "export")) { puts("Export is not authorized."); continue; }
            snprintf(job, sizeof(job), "report-%lld-%lu", (long long)time(NULL), (unsigned long)clock());
            if (!strcmp(command, "2")) {
                char *raw = ln_reserve(client, "export", 1, job);
                if (!raw) { show_error(client); continue; }
                cJSON *hold = ln_json(raw); ln_free_string(raw);
                cJSON *id = cJSON_GetObjectItemCaseSensitive(hold, "reservation_id"), *status = cJSON_GetObjectItemCaseSensitive(hold, "status");
                if (!cJSON_IsString(id) || !cJSON_IsString(status) || strcmp(status->valuestring, "pending")) { cJSON_Delete(hold); puts("Closed operation; do not execute it again."); continue; }
                snprintf(reservation, sizeof(reservation), "%s", id->valuestring); cJSON_Delete(hold);
            }
            if (!write_report()) {
                if (reservation[0]) { char *result = ln_cancel(client, reservation, job); ln_free_string(result); reservation[0] = 0; }
                fputs("Export failed; the reserved units were not committed.\n", stderr); continue;
            }
            puts("Report saved: licensed-report.txt");
            if (reservation[0]) {
                char *result = ln_commit(client, reservation, job);
                if (result) reservation[0] = 0; else show_error(client);
                ln_free_string(result);
            }
        }
    }
    if (reservation[0]) fputs("Commit is still pending. Production applications must persist the job before executing it.\n", stderr);
    ln_destroy(client); return 0;
}
