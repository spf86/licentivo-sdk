import {createInterface} from 'node:readline/promises';
import {stdin,stdout} from 'node:process';
import {writeFileSync} from 'node:fs';
import {randomUUID} from 'node:crypto';
import {Client} from './licentivo.mjs';
const input=createInterface({input:stdin,output:stdout});let client,pending,job;
const lines=input[Symbol.asyncIterator]();
async function ask(prompt){stdout.write(prompt);const line=await lines.next();return line.done?'0':line.value;}
try{
 const key=await ask('License key / transfer code (empty to restore): ');
 client=await Client.openWithLicense(process.argv[2]??'product.json',key,e=>console.error('Background verification:',e.message));
 client.onStatusChanged=s=>console.log('License:',s.state);
 for(;;){const choice=await ask('1 Export  2 Metered export  3 Retry commit  4 Release device  5 Status  0 Exit: ');if(choice==='0')break;
  try{
   if(choice==='5'){console.log(client.status());continue;}if(choice==='4'){await client.deactivate();continue;}
   if(choice==='3'){if(pending){console.log(await client.commit(pending.reservation_id,job));pending=null;}continue;}
   if(!['1','2'].includes(choice))continue;
   if(pending)throw Error('Finish the pending commit first.');const state=client.featureStatus('export');if(!state.allowed)throw Error(state.code||state.state);
   job=randomUUID();if(choice==='2'){pending=await client.reserve('export',1,job);if(pending.status!=='pending')throw Error('Closed operation; do not export again.');}
   try{writeFileSync('licensed-report.txt','A report generated by the licensed application.\n',{mode:0o600});}catch(e){if(pending){await client.cancel(pending.reservation_id,job);pending=null;}throw e;}
   if(pending){await client.commit(pending.reservation_id,job);pending=null;}console.log('Report saved: licensed-report.txt');
  }catch(e){console.error(e.message,e.requestID??'');if(pending)console.error('If the report was saved, retry only its commit.');}
 }
}finally{input.close();if(client)await client.close();}
