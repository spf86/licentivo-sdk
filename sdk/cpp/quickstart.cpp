#include "licentivo.hpp"
#include <cstdlib>
#include <fstream>
#include <iostream>

// BEGIN LICENTIVO PRODUCT
// Copy Product ID and all key ID/public key pairs from Console > Products > Signing public keys.
static const std::string PRODUCT_ID = "YOUR_PRODUCT_ID";
static const std::string TRUSTED_KEYS_JSON = R"({"YOUR_KEY_ID":"YOUR_PUBLIC_KEY"})";
// END LICENTIVO PRODUCT

static std::string setting(const char *name, const char *fallback) {
    const char *value = std::getenv(name);
    return value && value[0] ? value : fallback;
}

static void exportReport(const std::string &path) {
    // Replace this write with your existing, non-metered export operation.
    std::ofstream output(path);
    output << "A report generated by the licensed application.\n";
    output.close();
    if (!output) throw std::runtime_error("Export write failed");
}

int main() {
    try {
        // A GUI supplies customer input; an empty key restores a prior activation.
        auto client = licentivo::Client::ForProduct(PRODUCT_ID, TRUSTED_KEYS_JSON, setting("LICENTIVO_LICENSE_KEY", ""));
        client.Start();
        auto feature = setting("LICENTIVO_FEATURE", "export");
        auto path = setting("LICENTIVO_OUTPUT", "licensed-report.txt");
        if (setting("LICENTIVO_METERED", "") == "1")
            client.RunMeteredFeature(feature, 1, setting("LICENTIVO_OPERATION_ID", ""), [&] { exportReport(path); });
        else
            client.RunFeature(feature, [&] { exportReport(path); });
        std::cout << "License OK: " << feature << " is available\nExport completed: " << path << '\n';
        // Destruction belongs in application shutdown; it returns floating seats.
        return 0;
    } catch (const std::exception &error) {
        std::cerr << error.what() << '\n';
        return 2;
    }
}
