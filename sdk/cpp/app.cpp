// A small customer application. The key comes from its activation UI.
#include "licentivo.hpp"
#include <chrono>
#include <fstream>
#include <iostream>
#include <string>

int main(int argc, char **argv) {
    std::string key, command, reservation, job;
    std::cout << "License key / transfer code (empty to restore): "; std::getline(std::cin, key);
    try {
        licentivo::Client client(argc > 1 ? argv[1] : "product.json", key);
        client.Start();
        while (std::cout << "1 Export report  2 Metered export  3 Retry commit  4 Release device  5 Status  0 Exit\n", std::getline(std::cin, command)) {
            if (command == "0") break;
            try {
                if (command == "5") std::cout << client.Status() << '\n';
                else if (command == "4") client.Deactivate();
                else if (command == "3" && !reservation.empty()) { client.Commit(reservation, job); reservation.clear(); }
                else if (command == "1" || command == "2") {
                    if (!reservation.empty()) { std::cout << "Report exists. Retry only its commit.\n"; continue; }
                    if (!client.CheckFeature("export")) { std::cout << "Export is not authorized.\n"; continue; }
                    job = "report-" + std::to_string(std::chrono::system_clock::now().time_since_epoch().count());
                    if (command == "2") {
                        auto raw = client.Reserve("export", 1, job);
                        auto hold = ln_json(raw.c_str());
                        auto id = cJSON_GetObjectItemCaseSensitive(hold, "reservation_id");
                        auto status = cJSON_GetObjectItemCaseSensitive(hold, "status");
                        if (!cJSON_IsString(id) || !cJSON_IsString(status) || std::string(status->valuestring) != "pending") { cJSON_Delete(hold); throw std::runtime_error("Closed operation; do not execute again"); }
                        reservation = id->valuestring; cJSON_Delete(hold);
                    }
                    try {
                        std::ofstream file("licensed-report.txt", std::ios::trunc);
                        file.exceptions(std::ios::badbit | std::ios::failbit);
                        file << "A report generated by the licensed application.\n"; file.close();
                    } catch (...) {
                        if (!reservation.empty()) { try { client.Cancel(reservation, job); } catch (...) {} reservation.clear(); }
                        throw;
                    }
                    std::cout << "Report saved: licensed-report.txt\n";
                    if (!reservation.empty()) { client.Commit(reservation, job); reservation.clear(); }
                }
            } catch (const licentivo::APIError &error) { std::cerr << error.what() << "; request=" << error.details.request_id << '\n'; }
              catch (const std::exception &error) { std::cerr << error.what() << '\n'; }
        }
        if (!reservation.empty()) std::cerr << "Commit is pending. Production applications must persist the job before executing it.\n";
    } catch (const std::exception &error) { std::cerr << error.what() << '\n'; return 1; }
}
