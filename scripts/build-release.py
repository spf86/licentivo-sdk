#!/usr/bin/env python3
"""Build client-only release assets without server, database or payment access."""
import argparse
import hashlib
import json
import os
import pathlib
import platform
import re
import shutil
import subprocess
import tempfile
import zipfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
LANGUAGES = ("go", "java", "c", "cpp", "csharp", "python", "javascript", "rust", "ruby")
FIXED_TIME = (2026, 10, 9, 0, 0, 0)


def run(*command, cwd=ROOT):
    print("+ " + " ".join(map(str, command)), flush=True)
    subprocess.run(list(map(str, command)), cwd=cwd, check=True)


def archive(path, entries):
    with zipfile.ZipFile(path, "w", compression=zipfile.ZIP_DEFLATED) as output:
        for name, source in sorted(entries.items()):
            info = zipfile.ZipInfo(name, FIXED_TIME)
            info.create_system = 3  # Stable POSIX metadata on Windows and Linux.
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            data = source if isinstance(source, bytes) else source.read_bytes()
            output.writestr(info, data)


def public_files(directory):
    for path in sorted(directory.rglob("*")):
        relative = path.relative_to(directory)
        # This library's lockfile is generated by a build, not exported source.
        # Consumer applications retain their own Cargo.lock after installation.
        if path.name == 'Cargo.lock':
            continue
        if any(part in {"bin", "obj", "build", "dist", "target", "node_modules", "__pycache__"} or part.endswith(".egg-info") for part in relative.parts):
            continue
        if path.is_file() and path.suffix not in {".pyc", ".class", ".o", ".a", ".lib", ".dll", ".so", ".dylib", ".exe"}:
            if path.is_symlink():
                raise ValueError("Public source must not contain symlinks")
            yield relative.as_posix(), path


def source_bundle(language, output, version):
    entries = {name: ROOT / name for name in ("LICENSE", "NOTICE", "VERSION")}
    for name in ("README.md", "LICENSE", "NOTICE", "VERSION", "example-config.json"):
        entries["sdk/" + name] = ROOT / "sdk" / name
    entries["tests/lease-vectors.json"] = ROOT / "tests/lease-vectors.json"
    for name in ("README.md", "QUICKSTART.md", "start.ps1", "start.sh", "install.ps1", "install.sh"):
        entries[name] = ROOT / name
    entries.update({"docs/" + name: path for name, path in public_files(ROOT / "docs")})
    entries["SDK-LANGUAGE"] = (language + "\n").encode()
    if language == "go":
        entries["go.mod"] = ROOT / "go.mod"
        entries.update({path.name: path for path in ROOT.glob("*.go")})
        for prefix in ("internal/lease", "examples/go"):
            entries.update({prefix + "/" + name: path for name, path in public_files(ROOT / prefix)})
    else:
        folders = ("c", "cpp") if language in ("c", "cpp") else (language,)
        for folder in folders:
            entries.update({f"sdk/{folder}/{name}": path for name, path in public_files(ROOT / "sdk" / folder)})
        if language in ("c", "cpp"):
            for name in ("CMakeLists.txt", "LicentivoConfig.cmake.in"):
                entries["sdk/" + name] = ROOT / "sdk" / name
    name = f"licentivo-{language}-{version}.zip"
    archive(output / name, entries)
    return name


def metadata(version):
    checks = {
        "sdk/javascript/package.json": lambda text: json.loads(text)["version"] == version,
        "sdk/python/pyproject.toml": lambda text: f'version = "{version}"' in text,
        "sdk/java/pom.xml": lambda text: f"<version>{version}</version>" in text,
        "sdk/csharp/Licentivo.csproj": lambda text: f"<Version>{version}</Version>" in text,
        "sdk/CMakeLists.txt": lambda text: f"VERSION {version} " in text,
        "sdk/rust/Cargo.toml": lambda text: f'version = "{version}"' in text,
        "sdk/ruby/licentivo-sdk.gemspec": lambda text: f"spec.version = '{version}'" in text,
        "install.ps1": lambda text: f"$Version='{version}'" in text,
        "install.sh": lambda text: f"version={version}\n" in text,
    }
    for filename, check in checks.items():
        if not check((ROOT / filename).read_text(encoding="utf-8")):
            raise ValueError(f"Package version mismatch: {filename}")
    module = (ROOT / "go.mod").read_text(encoding="utf-8")
    if "module github.com/spf86/licentivo-sdk\n" not in module or "replace " in module:
        raise ValueError("The release must use the independently installable public Go module")


def native_build(args, output, version, work):
    windows = os.name == "nt"
    curl_root = pathlib.Path(args.curl_root).resolve() if args.curl_root else None
    native = work / "native"
    compiler = "mingw" if windows and curl_root else "msvc" if windows else "system"
    if curl_root:
        os.environ["PATH"] = str(curl_root / "bin") + os.pathsep + os.environ["PATH"]
    if shutil.which("cmake"):
        command = ["cmake", "-S", ROOT / "sdk", "-B", work / "native-build", "-DCMAKE_BUILD_TYPE=Release", f"-DCMAKE_INSTALL_PREFIX={native}"]
        if windows and curl_root:
            generator = "Ninja" if shutil.which("ninja") else "MinGW Makefiles"
            command += ["-G", generator, "-DCMAKE_C_COMPILER=gcc", "-DCMAKE_CXX_COMPILER=g++", f"-DCURL_INCLUDE_DIR={curl_root / 'include'}", f"-DCURL_LIBRARY={curl_root / 'lib/libcurl.dll.a'}"]
        run(*command)
        run("cmake", "--build", work / "native-build", "--config", "Release", "--parallel", "2")
        vector = work / "native-build" / ("licentivo_vectors.exe" if windows else "licentivo_vectors")
        if windows and not vector.exists():
            vector = work / "native-build/Release/licentivo_vectors.exe"
        run(vector, ROOT / "tests/lease-vectors.json")
        run("cmake", "--install", work / "native-build", "--config", "Release")
    elif windows and curl_root:
        for folder in ("lib", "include/licentivo/c/vendor", "include/licentivo/cpp", "lib/cmake/Licentivo", "licenses"):
            (native / folder).mkdir(parents=True, exist_ok=True)
        objects = []
        for source in ("licentivo", "vendor/monocypher", "vendor/monocypher-ed25519", "vendor/cJSON"):
            obj = work / (pathlib.Path(source).name + ".o")
            run("gcc", "-std=c11", "-O2", "-Wall", "-Wextra", f"-I{ROOT / 'sdk/c'}", f"-I{curl_root / 'include'}", "-c", ROOT / f"sdk/c/{source}.c", "-o", obj)
            objects.append(obj)
        library = native / "lib/liblicentivo_c.a"
        run("ar", "rcs", library, *objects)
        vector = work / "vectors.exe"
        run("gcc", "-std=c11", f"-I{ROOT / 'sdk/c'}", ROOT / "sdk/c/test_vectors.c", *objects, curl_root / "lib/libcurl.dll.a", "-lbcrypt", "-ladvapi32", "-o", vector)
        os.environ["PATH"] = str(curl_root / "bin") + os.pathsep + os.environ["PATH"]
        run(vector, ROOT / "tests/lease-vectors.json")
        # Compile the C++ wrapper with the exact same C objects and runtime ABI.
        run("g++", "-std=c++17", f"-I{ROOT / 'sdk/c'}", ROOT / "sdk/cpp/demo.cpp", *objects, curl_root / "lib/libcurl.dll.a", "-lbcrypt", "-ladvapi32", "-o", work / "cpp-consumer.exe")
        shutil.copyfile(ROOT / "sdk/c/licentivo.h", native / "include/licentivo/c/licentivo.h")
        for header in (ROOT / "sdk/c/vendor").glob("*.h"):
            shutil.copyfile(header, native / "include/licentivo/c/vendor" / header.name)
        shutil.copyfile(ROOT / "sdk/cpp/licentivo.hpp", native / "include/licentivo/cpp/licentivo.hpp")
        config = '''include(CMakeFindDependencyMacro)
find_dependency(CURL)
find_dependency(Threads)
get_filename_component(_licentivo_prefix "${CMAKE_CURRENT_LIST_DIR}/../../.." ABSOLUTE)
add_library(Licentivo::C STATIC IMPORTED)
set_target_properties(Licentivo::C PROPERTIES IMPORTED_LOCATION "${_licentivo_prefix}/lib/liblicentivo_c.a" INTERFACE_INCLUDE_DIRECTORIES "${_licentivo_prefix}/include/licentivo/c" INTERFACE_LINK_LIBRARIES "CURL::libcurl;Threads::Threads;bcrypt;advapi32")
add_library(Licentivo::CPP INTERFACE IMPORTED)
set_target_properties(Licentivo::CPP PROPERTIES INTERFACE_INCLUDE_DIRECTORIES "${_licentivo_prefix}/include/licentivo/cpp" INTERFACE_LINK_LIBRARIES Licentivo::C)
'''
        (native / "lib/cmake/Licentivo/LicentivoConfig.cmake").write_text(config, encoding="utf-8")
        (native / "lib/cmake/Licentivo/LicentivoConfigVersion.cmake").write_text(f'''set(PACKAGE_VERSION "{version}")
if(PACKAGE_FIND_VERSION VERSION_GREATER PACKAGE_VERSION)
  set(PACKAGE_VERSION_COMPATIBLE FALSE)
else()
  set(PACKAGE_VERSION_COMPATIBLE TRUE)
  if(PACKAGE_FIND_VERSION VERSION_EQUAL PACKAGE_VERSION)
    set(PACKAGE_VERSION_EXACT TRUE)
  endif()
endif()
''', encoding="utf-8")
        for source in (ROOT / "LICENSE", ROOT / "NOTICE", ROOT / "sdk/c/vendor/cJSON-LICENSE", ROOT / "sdk/c/vendor/Monocypher-LICENCE.md"):
            shutil.copyfile(source, native / "licenses" / source.name)
    else:
        raise ValueError("Install CMake and native dependencies, or provide --curl-root for a Windows MinGW build")
    shutil.copyfile(ROOT / "sdk/README.md", native / "README.md")
    shutil.copyfile(ROOT / "QUICKSTART.md", native / "QUICKSTART.md")
    readme = (native / "README.md").read_text(encoding="utf-8").replace("[QUICKSTART.md](../QUICKSTART.md)", "[QUICKSTART.md](QUICKSTART.md)")
    (native / "README.md").write_text(readme, encoding="utf-8")
    system = platform.system().lower()
    architecture = {"amd64": "x64", "x86_64": "x64", "aarch64": "arm64", "arm64": "arm64"}.get(platform.machine().lower(), platform.machine().lower())
    abi = "-" + compiler if windows else ""
    name = f"licentivo-native-{version}-{system}-{architecture}{abi}.zip"
    archive(output / name, dict(public_files(native)))
    # public_files deliberately ignores build binaries; native packages need the
    # compiled library in addition to their reviewable headers and notices.
    with zipfile.ZipFile(output / name, "a", compression=zipfile.ZIP_DEFLATED) as z:
        for library in sorted((native / "lib").rglob("*")):
            if library.is_file() and library.suffix in {".a", ".lib"}:
                info = zipfile.ZipInfo(library.relative_to(native).as_posix(), FIXED_TIME)
                info.create_system = 3
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = 0o100644 << 16
                z.writestr(info, library.read_bytes())
    return name


def checksum(output, assets, version):
    records = []
    for name in sorted(assets):
        data = (output / name).read_bytes()
        records.append({"name": name, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()})
    manifest = {"version": version, "repository": "spf86/licentivo-sdk", "artifacts": records}
    manifest_data = (json.dumps(manifest, indent=2) + "\n").encode()
    (output / "manifest.json").write_bytes(manifest_data)
    lines = [record["sha256"] + "  " + record["name"] for record in records]
    lines.append(hashlib.sha256(manifest_data).hexdigest() + "  manifest.json")
    (output / "SHA256SUMS").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return manifest


def binding_build(output, version, full):
    """Check the C-backed languages and emit the platform's compiler-free gem."""
    assets = []
    run("cargo", "test", "--manifest-path", "sdk/rust/Cargo.toml")
    run("cargo", "run", "--manifest-path", "sdk/rust/Cargo.toml", "--example", "vectors", "--", "tests/lease-vectors.json")
    if full:
        run("cargo", "package", "--manifest-path", "sdk/rust/Cargo.toml", "--allow-dirty", "--no-verify")
        crate = f"licentivo-{version}.crate"
        target = pathlib.Path(os.environ.get("CARGO_TARGET_DIR", str(ROOT / 'sdk/rust/target')))
        shutil.copyfile(target / "package" / crate, output / crate)
        assets.append(crate)
    run("ruby", "sdk/ruby/build_native.rb")
    run("ruby", "sdk/ruby/examples/vectors.rb", "tests/lease-vectors.json")
    if full:
        gem = f"licentivo-sdk-{version}.gem"
        run("ruby", "-S", "gem", "build", "licentivo-sdk.gemspec", "--output", output / gem, cwd=ROOT / "sdk/ruby")
        assets.append(gem)
    gem_platform = subprocess.check_output(["ruby", "-e", "require 'rubygems'; print Gem::Platform.local"], text=True).strip()
    if not re.fullmatch(r"[a-zA-Z0-9_-]+", gem_platform):
        raise ValueError("Unsafe Ruby platform name")
    platform_gem = f"licentivo-sdk-{version}-{gem_platform}.gem"
    os.environ['LICENTIVO_GEM_PRECOMPILED'] = '1'
    try:
        run("ruby", "-S", "gem", "build", "licentivo-sdk.gemspec", "--output", output / platform_gem, cwd=ROOT / "sdk/ruby")
    finally:
        os.environ.pop('LICENTIVO_GEM_PRECOMPILED', None)
    assets.append(platform_gem)
    return assets


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=pathlib.Path, default=pathlib.Path("dist"))
    parser.add_argument("--java-home", default=os.environ.get("JAVA_HOME", ""))
    parser.add_argument("--dotnet", default="dotnet")
    parser.add_argument("--curl-root", default=os.environ.get("LICENTIVO_CURL_ROOT", ""))
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--native-only", action="store_true")
    modes.add_argument("--bindings-only", action="store_true", help="Check Rust/Ruby; build the platform Ruby gem and C/C++ libraries")
    args = parser.parse_args()
    version = (ROOT / "VERSION").read_text().strip()
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise ValueError("Invalid VERSION")
    metadata(version)
    # Keep universal gems deterministic when built on more than one CI platform.
    os.environ.setdefault("SOURCE_DATE_EPOCH", "1791504000")
    output = args.out.resolve()
    output.mkdir(parents=True, exist_ok=True)
    (ROOT / ".local").mkdir(exist_ok=True)
    assets = []
    with tempfile.TemporaryDirectory(prefix="release-build-", dir=ROOT / ".local") as temp:
        work = pathlib.Path(temp)
        if not args.native_only and not args.bindings_only:
            assets.extend(source_bundle(language, output, version) for language in LANGUAGES)
            run("go", "test", "./...", "-count=1")
            run("go", "vet", "./...")
            run(os.sys.executable, "sdk/python/test_vectors.py", "tests/lease-vectors.json")
            run(os.sys.executable, "-m", "pip", "wheel", "--no-deps", "--no-build-isolation", "--wheel-dir", output, "sdk/python")
            assets.append(f"licentivo_sdk-{version}-py3-none-any.whl")
            npm = "npm.cmd" if os.name == "nt" else "npm"
            run("node", "sdk/javascript/test_vectors.mjs", "tests/lease-vectors.json")
            run(npm, "pack", "./sdk/javascript", "--pack-destination", output, "--ignore-scripts")
            assets.append(f"licentivo-sdk-{version}.tgz")
            java_bin = pathlib.Path(args.java_home) / "bin" if args.java_home else None
            javac = java_bin / ("javac.exe" if os.name == "nt" else "javac") if java_bin else "javac"
            java = java_bin / ("java.exe" if os.name == "nt" else "java") if java_bin else "java"
            classes = work / "java"
            classes.mkdir()
            run(javac, "-encoding", "UTF-8", "--release", "17", "-d", classes, *sorted((ROOT / "sdk/java/src/licentivo").glob("*.java")))
            run(java, "-cp", classes, "licentivo.TestVectors", ROOT / "tests/lease-vectors.json")
            entries = dict(public_files(classes))
            entries.update({path.relative_to(classes).as_posix(): path for path in classes.rglob("*.class")})
            entries["META-INF/MANIFEST.MF"] = f"Manifest-Version: 1.0\r\nImplementation-Title: Licentivo SDK\r\nImplementation-Version: {version}\r\n\r\n".encode()
            entries["META-INF/LICENSE"] = ROOT / "LICENSE"
            entries["META-INF/NOTICE"] = ROOT / "NOTICE"
            jar = f"licentivo-sdk-{version}.jar"
            archive(output / jar, entries)
            assets.append(jar)
            run(args.dotnet, "run", "--project", "sdk/csharp/demo/Demo.csproj", "--", "--vectors", "tests/lease-vectors.json")
            run(args.dotnet, "pack", "sdk/csharp/Licentivo.csproj", "-c", "Release", "-o", output, "--nologo")
            assets.append(f"Licentivo.SDK.{version}.nupkg")
            for name in ("install.ps1", "install.sh"):
                shutil.copyfile(ROOT / name, output / name)
                assets.append(name)
        if not args.native_only:
            if args.bindings_only:
                assets.append(source_bundle('rust', output, version))
                for name in ("install.ps1", "install.sh"):
                    shutil.copyfile(ROOT / name, output / name)
                    assets.append(name)
            assets.extend(binding_build(output, version, not args.bindings_only))
        assets.append(native_build(args, output, version, work))
    manifest = checksum(output, assets, version)
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
